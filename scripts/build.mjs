// Builds public/ (what Netlify serves) and the CSS the reconfirm page inlines.
//   public/ra-booking.js   strings (config/strings.en.js) + widget/ra-booking.js, one script to embed
//   public/ra-booking.css  scoped widget styles
//   public/demo.html, demo.js, mock-stripe.html   local demo only (not linked from the site)
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { strings } from '../config/strings.en.js';

mkdirSync('public', { recursive: true });
// Write only when the content changed: `wrangler dev` watches these files and would rebuild forever.
const put = (path, text) => { if (!existsSync(path) || readFileSync(path, 'utf8') !== text) writeFileSync(path, text); };
const widget = readFileSync('widget/ra-booking.js', 'utf8');
put('public/ra-booking.js', `window.RA_BK_STRINGS=${JSON.stringify(strings)};\n${widget}`);
put('public/ra-booking.css', readFileSync('widget/ra-booking.css', 'utf8'));
for (const f of ['demo.html', 'demo.js', 'mock-stripe.html']) put(`public/${f}`, readFileSync(`widget/${f}`, 'utf8'));

const css = readFileSync('widget/ra-booking.css', 'utf8');
put('src/lib/css.generated.js', `// Generated by scripts/build.mjs from widget/ra-booking.css. Do not edit.\nexport const css = ${JSON.stringify(css)};\n`);
console.log('built public/ and css.generated.js');
