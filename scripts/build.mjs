// Builds public/ (what Netlify serves) and the CSS the reconfirm page inlines.
//   public/ra-booking.js   strings (config/strings.en.js) + widget/ra-booking.js, one script to embed
//   public/ra-booking.css  scoped widget styles
//   public/demo.html, demo.js, mock-stripe.html   local demo only (not linked from the site)
import { readFileSync, writeFileSync, mkdirSync, copyFileSync } from 'node:fs';
import { strings } from '../config/strings.en.js';

mkdirSync('public', { recursive: true });
const widget = readFileSync('widget/ra-booking.js', 'utf8');
writeFileSync('public/ra-booking.js', `window.RA_BK_STRINGS=${JSON.stringify(strings)};\n${widget}`);
copyFileSync('widget/ra-booking.css', 'public/ra-booking.css');
for (const f of ['demo.html', 'demo.js', 'mock-stripe.html']) copyFileSync(`widget/${f}`, `public/${f}`);

const css = readFileSync('widget/ra-booking.css', 'utf8');
writeFileSync('netlify/functions/_lib/css.generated.js', `// Generated by scripts/build.mjs from widget/ra-booking.css. Do not edit.\nexport const css = ${JSON.stringify(css)};\n`);
console.log('built public/ and css.generated.js');
